"""(hookshot) The Insert menu's PlayStation button icons (gpu/vk/vk_menu.cpp) from assets/pad_icons/playstation/png128: a C
header with each icon's coverage, 64 x 64 bytes (the white outline's alpha, averaged over 2 x 2), in the order of the
gamepad's inputs (HOS_PAD_*, gpu/vk/vk_api.h). Written by nx2/build.py into the build's own folder, as nx2/logo_rgba.py
writes the logo's. The icons: "PS5 Button Icons and Controls" by Zacksly, CC BY 3.0 (assets/pad_icons/playstation/CREDITS.txt).

    python nx2/pad_icons_rgba.py [out.h]

Standard library only (logo_rgba's PNG decoder).
"""
import os
import sys

import logo_rgba

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SOURCE = os.path.join(ROOT, "assets", "pad_icons", "playstation", "png128")
SIZE = 64
# (HOS_PAD_SOUTH ... HOS_PAD_RTRIGGER; None: no icon, the name alone. The PS button's would be the PlayStation logo)
ICONS = ["Cross", "Circle", "Square", "Triangle", "Create", None, "Options", "Left Stick Click", "Right Stick Click",
         "L1", "R1", "D-Pad Up", "D-Pad Down", "D-Pad Left", "D-Pad Right", "L2", "R2"]


def coverage(path):
    """The icon's alpha at SIZE x SIZE, a box filter from its size (a multiple of SIZE)"""
    w, h, px = logo_rgba.decode(open(path, "rb").read())
    if w != h or w % SIZE:
        raise ValueError("%s: %dx%d, not a square multiple of %d" % (path, w, h, SIZE))
    k = w // SIZE
    out = bytearray(SIZE * SIZE)
    for y in range(SIZE):
        for x in range(SIZE):
            total = 0
            for dy in range(k):
                row = ((y * k + dy) * w + x * k) * 4
                total += sum(px[row + 4 * dx + 3] for dx in range(k))
            out[y * SIZE + x] = (total + k * k // 2) // (k * k)
    return bytes(out)


def header(src=SOURCE):
    if not all(n is None or os.path.isfile(os.path.join(src, n + ".png")) for n in ICONS):
        return "// generated by nx2/pad_icons_rgba.py: no assets/pad_icons/playstation\n#pragma once\n"
    lines = ["// generated by nx2/pad_icons_rgba.py from assets/pad_icons/playstation (Zacksly, CC BY 3.0): do not edit",
             "#pragma once",
             "#define HOOKSHOT_PAD_ICONS 1",
             "static const unsigned pad_icon_size = %d;" % SIZE,
             "static const unsigned char pad_icon_has[%d] = {%s};" % (len(ICONS), ",".join("0" if n is None else "1" for n in ICONS)),
             "static const unsigned char pad_icon_alpha[%d][%d] = {" % (len(ICONS), SIZE * SIZE)]
    for n in ICONS:
        a = bytes(SIZE * SIZE) if n is None else coverage(os.path.join(src, n + ".png"))
        lines.append("{" + ",".join(str(b) for b in a) + "},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def write(out_path, src=SOURCE):
    """Writes the header when it differs (an unchanged one keeps its timestamp); returns its text"""
    text = header(src)
    try:
        with open(out_path, encoding="utf-8") as f:
            if f.read() == text:
                return text
    except OSError:
        pass
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return text


if __name__ == "__main__":
    sys.stdout.write("%d bytes\n" % len(write(sys.argv[1] if len(sys.argv) > 1 else "hookshot_pad_icons.h")))
